-- 165_ocr_source_file.sql — ocr_jobs 记住"这次识别是从哪个上传件发起的"
--
-- 由来(2026-09-29): OCR 的产物原本只落在 `ocr_jobs.text` 里, 而审稿/对话要的是
--   「这个**上传文件**的正文」—— 两者在库里没有任何连接点。后果不是报错, 是**绕不回来的圈**:
--   用户拿扫描件去审稿 → 系统说"没有文字层, 去识别文字" → 用户识别完回到评审页重选文件
--   → 系统**还是**说"没有文字层"。因为重新选文件是**另一次上传**, 产生的是新的 user_files 行,
--   OCR 结果写不回那一行。
--
-- 有了这一列, 识别完成时就能把正文写回**发起它的那份文件**(ocr-job-service 的收尾),
-- 于是"识别 → 回来审"这条回程成立。
--
-- 为什么单独一个迁移而不是并进 164:
--   ⚠ 164 在本机**已经应用过了**(先跑了一次 migrate 才发现还要加这列)。
--     迁移表按文件名记录, 已应用的不会重跑 —— 把新语句补进旧文件, 本机永远不会执行,
--     于是"我改了啊"和"库里没有"同时成立。这正是本仓 schema 漂移自检拦的那类问题。
--
-- 允许为空: 直接传字节发起的识别(写作舱素材上传那条既有路径)没有对应的上传件, 不能强制。

alter table if exists ocr_jobs add column if not exists source_file_id text not null default '';

comment on column ocr_jobs.source_file_id is
  'V421 发起这次识别的 user_files.id(裸 uuid). 完成后正文写回该文件的 text 列; 空 = 直接传字节发起的';
