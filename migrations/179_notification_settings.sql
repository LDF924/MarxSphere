-- 179_notification_settings.sql — 通知偏好(按分类静音)(2026-10-02)
--
-- 由来: 通知中心(迁移 175)能把消息送到用户面前了, 但**没有任何办法让它闭嘴** ——
--   五个分类(task/points/payment/digest/system)一视同仁地写库, 用户不想看"研究速递"
--   也关不掉。这类"只能开不能关"的通知系统, 用户的对策通常是干脆不看通知中心,
--   于是重要通知(支付失败)也被一起忽略 —— 比没有通知更糟。
--
-- ⚠ 为什么落库(jsonb)而不是 localStorage:
--   通知是**服务端写**的。若偏好只存在浏览器里, 服务端无从知道该不该写这一条,
--   只能"照写不误 + 前端隐藏" —— 那用户换个设备/换个浏览器就会看到一堆自己关过的通知。
--   真正要省的是"别写库、别推送", 所以偏好必须在服务端。
--
-- 语义: 存**被静音的**分类数组, 而不是"开启的"数组。
--   新增分类时默认是**响**(不出现在列表里), 与"默认不打扰"的直觉相反但更正确:
--   静音是用户显式选择的结果, 没选过的新分类不该被静默吞掉 —— 否则加一个分类
--   等于给所有人默认关掉它, 而且没人会发现。
alter table users
  add column if not exists notification_muted jsonb not null default '[]'::jsonb;

comment on column users.notification_muted is
  '被静音的通知分类数组, 如 ["digest","points"]。空数组=全部接收。新增分类默认接收。';
